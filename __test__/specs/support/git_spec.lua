local git = require("__test__.support.git")
local t = require("__test__.support.harness").new()

t:test("a repository commits as the fixed identity and git failures raise with stderr", function()
  local root = git.repo(t)
  vim.fn.writefile({ "content" }, root .. "/file")
  git.run(root, { "add", "file" })
  git.run(root, { "commit", "-qm", "base" })
  t.assert_eq("Test <test@example.com>\n", git.run(root, { "log", "-1", "--format=%an <%ae>" }))
  t.assert_error(function()
    git.run(root, { "rev-parse", "--verify", "missing" })
  end, "git rev-parse --verify missing: exit", "nonzero exit")
  t.assert_true(git.system(root, { "rev-parse", "--verify", "missing" }).code ~= 0)
end)

t:test("commit records every change and init creates a repository inside another", function()
  local root = git.repo(t)
  vim.fn.writefile({ "content" }, root .. "/file")
  git.commit(root, "base")
  t.assert_eq("base\n", git.run(root, { "log", "-1", "--format=%s" }))
  t.assert_eq("", git.run(root, { "status", "--porcelain" }), "nothing left uncommitted")
  local nested = root .. "/nested"
  vim.fn.mkdir(nested)
  git.init(nested)
  t.assert_eq(nested .. "/.git\n", git.run(nested, { "rev-parse", "--absolute-git-dir" }))
  t.assert_eq("false\n", git.run(nested, { "config", "core.autocrlf" }))
end)

t:run()
